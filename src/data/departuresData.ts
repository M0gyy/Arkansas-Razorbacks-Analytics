// Helper functions
export function getDeparturesBySeason(season?: number | 'ALL'): PlayerDeparture[] {
  if (!season || season === 'ALL') {
    return DEPARTURES_DATA;
  }
  return DEPARTURES_DATA.filter((d) => d.season === season);
}

export function getDepartureSummaryBySeason() {
  const seasons = Array.from(new Set(DEPARTURES_DATA.map((d) => d.season))).sort((a, b) => a - b);
  return seasons.map((yr) => {
    const list = DEPARTURES_DATA.filter((d) => d.season === yr);
    const totalSnaps = list.reduce((acc, d) => acc + d.snap_count, 0);
    const offPlayers = list.filter((d) => ['QB', 'RB', 'WR', 'TE', 'OL'].includes(d.position));
    const defPlayers = list.filter((d) => ['DL', 'LB', 'DB', 'S'].includes(d.position));
    
    const offEpaLost = offPlayers.reduce((acc, d) => acc + d.total_epa_impact, 0);
    const defEpaLost = defPlayers.reduce((acc, d) => acc + d.total_epa_impact, 0);

    const draftCount = list.filter((d) => d.exit_type.toLowerCase().includes('draft')).length;
    const portalCount = list.filter((d) => d.exit_type.toLowerCase().includes('portal') || d.exit_type.toLowerCase().includes('transfer')).length;
    const gradCount = list.filter((d) => d.exit_type.toLowerCase().includes('grad')).length;

    return {
      season: yr,
      totalDepartures: list.length,
      totalSnaps,
      offEpaLost: Number(offEpaLost.toFixed(1)),
      defEpaLost: Number(defEpaLost.toFixed(1)),
      draftCount,
      portalCount,
      gradCount,
      topPlayerLost: list.reduce((max, cur) => Math.abs(cur.total_epa_impact) > Math.abs(max.total_epa_impact) ? cur : max, list[0])?.player_name || 'N/A'
    };
  });
}
